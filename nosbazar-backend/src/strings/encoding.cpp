        {
            if (c < 0x80)
            {
                result.push_back(c);
            }
            else
            {
                const unsigned char* entry = table[c - 0x80];
                result.append(reinterpret_cast<const char*>(entry + 1), entry[0]);
            }
        }

        return result;
